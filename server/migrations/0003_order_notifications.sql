CREATE TABLE IF NOT EXISTS order_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  order_id BIGINT NOT NULL,
  channel VARCHAR(20) NOT NULL,
  recipient VARCHAR(255) NOT NULL,
  event_type VARCHAR(60) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'not_configured',
  provider_message_id VARCHAR(255) NULL,
  error_message TEXT NULL,
  payload_json JSONB NULL,
  sent_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT order_notifications_order_fk FOREIGN KEY (order_id) REFERENCES shop_orders(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS order_notifications_order_idx ON order_notifications (order_id, created_at);
CREATE INDEX IF NOT EXISTS order_notifications_status_idx ON order_notifications (status, channel);
