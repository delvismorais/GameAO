ALTER TABLE shop_orders ADD COLUMN IF NOT EXISTS invoice_template VARCHAR(32) NOT NULL DEFAULT 'classic';
ALTER TABLE shop_orders ADD COLUMN IF NOT EXISTS invoice_issued_at TIMESTAMPTZ NULL;

CREATE TABLE IF NOT EXISTS invoice_downloads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  order_id BIGINT NOT NULL,
  template VARCHAR(32) NOT NULL,
  downloaded_by_user_id BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT invoice_downloads_order_fk FOREIGN KEY (order_id) REFERENCES shop_orders(id) ON DELETE CASCADE,
  CONSTRAINT invoice_downloads_user_fk FOREIGN KEY (downloaded_by_user_id) REFERENCES app_users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS invoice_downloads_order_idx ON invoice_downloads (order_id, created_at);
